create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null,
  full_name text not null default '',
  role text not null default 'student' check (role in ('student','admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.access_events (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  event_type text not null check (event_type in ('login','page_view','lesson_view','quiz_complete')),
  page text not null default '' check (char_length(page) <= 200),
  created_at timestamptz not null default now()
);
create index if not exists access_events_user_date_idx on public.access_events(user_id,created_at desc);
create index if not exists access_events_date_idx on public.access_events(created_at desc);

-- Only the auth trigger may create a profile; user clients cannot change their role.
create or replace function public.create_meef_profile()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  insert into public.profiles (id,email,full_name,role)
  values (new.id, coalesce(new.email,''), left(coalesce(new.raw_user_meta_data ->> 'full_name',''),120), 'student')
  on conflict (id) do nothing;
  return new;
end;
$$;
drop trigger if exists meef_new_auth_user on auth.users;
create trigger meef_new_auth_user after insert on auth.users
  for each row execute function public.create_meef_profile();

-- If identities were created before setup, backfill safe default student roles.
insert into public.profiles(id,email,full_name,role)
select id,coalesce(email,''),left(coalesce(raw_user_meta_data ->> 'full_name',''),120),'student'
from auth.users on conflict(id) do nothing;

create schema if not exists private;
create or replace function private.meef_is_admin()
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (select 1 from public.profiles where id = (select auth.uid()) and role='admin');
$$;
revoke all on function private.meef_is_admin() from public;
grant usage on schema private to authenticated;
grant execute on function private.meef_is_admin() to authenticated;

alter table public.profiles enable row level security;
alter table public.access_events enable row level security;

revoke all on public.profiles from anon, authenticated;
revoke all on public.access_events from anon, authenticated;
grant select on public.profiles to authenticated;
grant select,insert on public.access_events to authenticated;
grant usage,select on sequence public.access_events_id_seq to authenticated;

drop policy if exists "profiles: self or admin read" on public.profiles;
create policy "profiles: self or admin read" on public.profiles
for select to authenticated using ((select auth.uid()) = id or (select private.meef_is_admin()));

drop policy if exists "events: insert own only" on public.access_events;
create policy "events: insert own only" on public.access_events
for insert to authenticated with check ((select auth.uid()) = user_id);

drop policy if exists "events: admin read" on public.access_events;
create policy "events: admin read" on public.access_events
for select to authenticated using ((select private.meef_is_admin()));

